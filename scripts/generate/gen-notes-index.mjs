// gen-notes-index.mjs —— notes/ 的生成索引：一个找卡的入口，不是第二份清单。
//
// 为什么是生成物而不是手维护清单：手维护清单必然漂移（notes/README「刻意不做」旧裁决的痛点）；
// 生成 + freshness 门禁（pnpm verify 的 `gen-notes-index --check`）让漂移在提交前红，
// 与 gen-catalog / gen-paths 同一范式（生成物登记表：docs/dev.md §二）。
// 只从每张卡读两件事实——文件名日期、首个 `# ` 标题；状态词与目录的一致性由 notesStateProblems
// 另行把门，本索引不重复校验、不复制正文，一律链接过去。渲染核导出可夹具化
// （tests/tooling/verify-gates.spec.mjs 在 throwaway notes 树上钉接受/拒绝形状）。

import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// 三个活跃生命周期目录（archived 是冻结历史，只给指针不逐卡列——见 renderIndex 尾节）。
const SECTIONS = [
  ['implemented', 'implemented（当前 rationale owner）'],
  ['proposed', 'proposed（将来 · 待用户拍板）'],
  ['rejected', 'rejected（被否决的提案 · 负知识）'],
]

function firstHeading(text) {
  const line = text.split('\n').find(candidate => candidate.startsWith('# '))
  return line ? line.replace(/^#\s+/, '').trim() : '（无标题）'
}

function scan(notesRoot, sub) {
  const dir = join(notesRoot, sub)
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter(name => /^\d{4}-\d{2}-\d{2}-[a-z0-9][a-z0-9-]*\.md$/.test(name))
    .sort()
    .reverse()
    .map(name => ({ name, title: firstHeading(readFileSync(join(dir, name), 'utf8')) }))
}

/** 渲染核：收 notes 根路径，返回完整 INDEX 文本（纯函数，供 CLI 与夹具共用）。 */
export function renderIndex(notesRoot) {
  const lines = []
  lines.push('<!-- GENERATED by scripts/generate/gen-notes-index.mjs — do not edit by hand; run `pnpm gen-notes-index`. -->')
  lines.push('')
  lines.push('# notes 索引（生成物）')
  lines.push('')
  lines.push('> 找卡的入口，不是第二份清单：只读文件名日期与首个标题两件事实，正文一律链接过去；')
  lines.push('> 状态语义、取代检查与生命周期见 [README.md](README.md)。freshness 由 `pnpm verify`')
  lines.push('> （`gen-notes-index --check`）守——改了卡没重生成即红。关键词不在标题里时，')
  lines.push('> `grep -il \'<关键词>\' notes/implemented/` 全文搜是兜底。')
  lines.push('')
  for (const [sub, label] of SECTIONS) {
    const notes = scan(notesRoot, sub)
    lines.push(`## ${label}（${notes.length}）`)
    lines.push('')
    if (notes.length === 0) {
      lines.push('（空）')
      lines.push('')
      continue
    }
    lines.push('| 日期 | 卡 |')
    lines.push('|---|---|')
    for (const { name, title } of notes) {
      lines.push(`| ${name.slice(0, 10)} | [${title.replaceAll('|', '\\|')}](${sub}/${name}) |`)
    }
    lines.push('')
  }
  lines.push('## archived（冻结历史，不逐卡列）')
  lines.push('')
  lines.push('已收卷的低决策价值历史与调研台账住在 notes/archived/ 子树——按目录树读，不在本索引维护第二份清单。')
  lines.push('')
  return lines.join('\n')
}

// CLI：`node scripts/generate/gen-notes-index.mjs` 写入；`--check` 过期即红（进 pnpm verify 链）。
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const notesRoot = join(import.meta.dirname, '..', '..', 'notes')
  const target = join(notesRoot, 'INDEX.md')
  const rendered = renderIndex(notesRoot)
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
    if (current !== rendered) {
      console.error('gen-notes-index: notes/INDEX.md is stale — run `pnpm gen-notes-index` and commit the result')
      process.exit(1)
    }
    console.log('gen-notes-index: notes/INDEX.md is current')
  } else {
    writeFileSync(target, rendered)
    console.log(`gen-notes-index: wrote ${target}`)
  }
}
