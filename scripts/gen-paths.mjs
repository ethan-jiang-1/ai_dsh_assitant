#!/usr/bin/env node
/**
 * Generate `tsconfig.tsx.json`, the runtime resolution facade for launching the harness from source.
 * Run with `pnpm gen-paths`.
 *
 * Why a separate file: `tsc` must see only the packages this plugin imports directly (each paired
 * with a project reference), because resolving the whole DSH graph to `src` would pull their sources
 * into our program and collide with our `rootDir`. But **tsx** needs the opposite — the harness's own
 * modules are loaded by name at run time, and without a complete facade they resolve to
 * `lib/index.js`, which only exists after the harness's own tsdown build.
 *
 * So the two facades are separate on purpose:
 *   tsconfig.base.json   compile-time: the hand-written short list, with project references
 *   tsconfig.tsx.json    run time: every pinned package → its src, generated from the filesystem
 *
 * The generated file cannot drift: `pnpm verify` regenerates it and fails when it differs.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const vendorDsh = join(repoRoot, 'vendor', 'dsh')
const outputFile = join(repoRoot, 'tsconfig.tsx.json')

/** `statSync` that answers "no" instead of throwing on a missing path or a non-directory parent. */
function isDirectory(path) {
  try {
    return statSync(path).isDirectory()
  } catch {
    return false
  }
}

function isFile(path) {
  try {
    return statSync(path).isFile()
  } catch {
    return false
  }
}

/** Directories that hold one package each. */
function packageDirs() {
  const dirs = []
  for (const group of readdirSync(join(vendorDsh, 'packages'))) {
    const groupDir = join(vendorDsh, 'packages', group)
    if (!isDirectory(groupDir)) continue
    for (const name of readdirSync(groupDir)) {
      const dir = join(groupDir, name)
      if (isFile(join(dir, 'package.json'))) dirs.push(dir)
    }
  }
  for (const root of [join(vendorDsh, 'vendor'), join(vendorDsh, 'apps')]) {
    for (const name of readdirSync(root)) {
      const dir = join(root, name)
      if (isFile(join(dir, 'package.json'))) dirs.push(dir)
    }
  }
  return dirs
}

/** `@deepseek-ai/<name>` → `./<dir>/src`, for every pinned package that has a src/ directory. */
export function aliases() {
  const entries = new Map()
  for (const dir of packageDirs()) {
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    const name = manifest.name
    if (typeof name !== 'string' || !name.startsWith('@deepseek-ai/')) continue
    if (!isDirectory(join(dir, 'src'))) continue
    entries.set(name, `./${relative(repoRoot, join(dir, 'src')).split('\\').join('/')}`)
  }
  return [...entries.entries()].sort(([left], [right]) => left.localeCompare(right))
}

/** Render the whole generated tsconfig. */
export function render() {
  const paths = aliases()
    .map(([name, target]) => `      ${JSON.stringify(name)}: [${JSON.stringify(target)}]`)
    .join(',\n')
  return `{
  // GENERATED by scripts/gen-paths.mjs — do not edit by hand; run \`pnpm gen-paths\`.
  //
  // Runtime resolution facade for \`pnpm dsh\` (node --import tsx/esm): tsx resolves
  // \`@deepseek-ai/*\` through the nearest tsconfig's \`paths\`, so this file is what lets the harness
  // load the pinned sources instead of unbuilt \`lib/index.js\`. ${paths.split('\n').length} aliases,
  // regenerated from vendor/dsh on every pin change.
  "extends": "./tsconfig.base.json",
  "compilerOptions": {
    "paths": {
${paths}
    }
  }
}
`
}

const current = isFile(outputFile) ? readFileSync(outputFile, 'utf8') : ''
const next = render()
const check = process.argv.includes('--check')

if (check) {
  if (current !== next) {
    console.error('gen-paths: tsconfig.tsx.json is stale — run `pnpm gen-paths`')
    process.exit(1)
  }
  console.log(`gen-paths: up to date (${aliases().length} runtime aliases)`)
} else {
  writeFileSync(outputFile, next, 'utf8')
  console.log(`gen-paths: wrote ${aliases().length} runtime aliases to tsconfig.tsx.json`)
}
