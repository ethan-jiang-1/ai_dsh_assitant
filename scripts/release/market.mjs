#!/usr/bin/env node
// 何时跑：npm 上已经发布过至少一个版本之后（顺序锁死——generator 只读 registry，不吃本地 tarball）。
// 用法：pnpm market [--title "…"] [--input <包名>] [--check]
//
// 市场索引是**发现层**，不是分发层：DSH 出厂不配任何索引，用户在 Discover 里自己加 URL，
// 而自定义市场 bundle（@deepseek-ai/dsh-experimental-plugin-market-bundle）出厂关着。
// 所以这一步的产物是"可托管的静态目录"，不是"发布"——发布永远是 npm 那一步（docs/release.md §二）。
//
// 为什么调官方 generator 而不是自己拼 JSON：索引格式（format 1）有生成者义务——version/publishTimestamp/
// engines.dsh/dist-tags 必须与 registry 一致，title/description/icon 要按"已安装插件的显示规则"取。
// 自己拼一份就是第二套实现，且必须跟着 format 走（docs 明确：generator 的违约读者查不出来）。
//
// 产物：_dist/market/{index.json, icons/…}——把整个目录静态托管到 https 即可。
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const packageDir = join(repoRoot, 'packages', 'dsh-smart-assistant')
const outDir = join(repoRoot, '_dist', 'market')
const validatorPath = join(repoRoot, 'vendor', 'dsh', 'packages', 'util', 'plugin-market-index', 'lib', 'index.js')
const generatorBin = join(repoRoot, 'vendor', 'dsh', 'apps', 'plugin-market-generator', 'src', 'bin.ts')
// The generator is a vendored DSH app, not a member of this workspace (`pnpm-workspace.yaml` only
// pulls `vendor/dsh/packages`, `vendor/dsh/vendor`, and the two apps it needs to build). Run its
// TypeScript entry with the vendor checkout's own tsx instead of inventing a second workspace entry.
const generatorTsx = join(repoRoot, 'vendor', 'dsh', 'node_modules', '.bin', 'tsx')

const argOf = (name, fallback) => {
  const index = process.argv.indexOf(name)
  return index === -1 ? fallback : process.argv[index + 1]
}
const manifest = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'))
const packageName = argOf('--input', manifest.name)
const title = argOf('--title', 'DSH Smart Assistant')

if (!existsSync(validatorPath)) {
  console.error(`market: ${validatorPath} is missing — run \`pnpm install && pnpm build\` (or \`bash dev/env/prepare.sh\`) first`)
  process.exit(2)
}

mkdirSync(outDir, { recursive: true })
const inputPath = join(repoRoot, '.tmp', 'market', 'plugins.txt')
mkdirSync(dirname(inputPath), { recursive: true })
writeFileSync(inputPath, `# Generated by scripts/release/market.mjs — the official generator reads this list.\n${packageName}\n`, 'utf8')

if (!existsSync(generatorTsx) || !existsSync(generatorBin)) {
  console.error(`market: the vendored generator is not runnable (missing ${existsSync(generatorTsx) ? generatorBin : generatorTsx}) — run \`git submodule update --init && pnpm install\``)
  process.exit(2)
}
const generated = spawnSync(generatorTsx, [
  generatorBin,
  '--input', inputPath,
  '--output', join(outDir, 'index.json'),
  '--title', title,
  '--cache', join(repoRoot, '.tmp', 'market-cache'),
], { cwd: repoRoot, encoding: 'utf8' })
const output = `${generated.stdout ?? ''}${generated.stderr ?? ''}`.trim()
const indexPath = join(outDir, 'index.json')
if (generated.status !== 0 || !existsSync(indexPath)) {
  // Never leave a partial or empty index in the publishable directory: a hosted 0-plugin index is
  // a market listing that silently advertises nothing.
  rmSync(indexPath, { force: true })
  console.error(`market: the generator could not read every source (exit ${generated.status}):`)
  console.error(output.split('\n').slice(-12).join('\n'))
  console.error(`\nmarket: 索引只读 registry——先在 npm 上发布 ${packageName}（docs/release.md §二），再跑这一步。`)
  process.exit(1)
}

// Validate with the same rule set DSH's own reader uses. A generator bug must fail here, not in a
// user's Discover tab.
const { parseMarketIndex, marketInstallTarget } = await import(validatorPath)
const document = JSON.parse(readFileSync(indexPath, 'utf8'))
let index
try {
  index = parseMarketIndex(document, 'https://example.invalid/market/index.json')
} catch (error) {
  console.error(`market: _dist/market/index.json is not a valid format-1 index: ${String(error)}`)
  process.exit(1)
}
const entry = index.plugins.find(plugin => plugin.name === packageName)
if (entry === undefined) {
  rmSync(indexPath, { force: true })
  console.error(`market: the generator listed no version of ${packageName} (deprecated, no bundle declaration, or no compatible engines.dsh?)`)
  process.exit(1)
}
const latest = entry['dist-tags']?.latest
const latestVersion = entry.versions.find(version => version.version === latest) ?? entry.versions[0]
const target = marketInstallTarget(entry.name, latestVersion.version)
const englishTitle = typeof entry.title === 'string' ? entry.title : entry.title?.en
console.log(`market: ${entry.name} — ${entry.versions.length} version(s), latest ${latestVersion.version}`)
console.log(`market: title 「${englishTitle ?? '(falls back to the package name)'}」, install spec ${target.spec}`)
console.log(`market: output _dist/market/index.json (host the whole directory over https, then add the URL in Discover)`)
if (englishTitle === undefined || englishTitle === entry.name) {
  console.error('market: the title fell back to the package name — locale/en.json is missing or unreadable')
  process.exit(1)
}
if (process.argv.includes('--check')) console.log('market: --check ok (nothing else to do)')
