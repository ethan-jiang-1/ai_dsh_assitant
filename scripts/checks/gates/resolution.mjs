/**
 * Gate cores about resolution and gate self-wiring: project reference shape and the
 * rule that every exported core must actually be invoked by verify.mjs.
 */
import { join, relative, resolve } from 'node:path'
import { projectReferenceMatches } from './shared.mjs'


// ── import resolution (the runner reads the corpus, these cores judge it) ────────────────────

/**
 * Every `@deepseek-ai/*` import must have a paths entry in `tsconfig.base.json`, and that entry's
 * owning project must be referenced by the package's tsconfig with an `index.ts` at the target.
 * @param {{ repoRoot: string, packageDir: string, baseText: string, projectConfigText: string,
 *   sources: { path: string, text: string }[], exists: (path: string) => boolean }} inputs -
 * the two config texts, every package source, and an existence predicate.
 * @returns {string[]} one problem per unbacked import; empty when every import resolves.
 */
export function importResolutionProblems({ repoRoot, packageDir, baseText, projectConfigText, sources, exists }) {
  const problems = []
  const pathsKeys = new Set([...baseText.matchAll(/^\s*"(@deepseek-ai\/[^"]+)":/gm)].map(match => match[1]))
  // References are written relative to the package directory; compare absolute paths so the two
  // spellings of the same project cannot look like a mismatch.
  const references = new Set([...projectConfigText.matchAll(/"path":\s*"([^"]+)"/g)]
    .map(match => resolve(packageDir, match[1])))
  const imported = new Set()
  for (const source of sources) {
    for (const match of source.text.matchAll(/from\s+'(@deepseek-ai\/[^']+)'/g)) imported.add(match[1])
  }
  for (const specifier of imported) {
    if (!pathsKeys.has(specifier)) {
      problems.push(`${specifier} is imported but has no paths entry in tsconfig.base.json`)
      continue
    }
    const target = new RegExp(`"${specifier.replace(/[/\\^$*+?.()|[\]{}]/g, '\\$&')}":\\s*\\["([^"]+)"\\]`).exec(baseText)?.[1]
    if (target === undefined) continue
    // Package-root entries end at a `src` directory; client-face entries end at `src/<subpath>`
    // (the vendor convention, e.g. `pkg/client` → `<pkg>/src/client`). In both cases the owning
    // project is the package directory the `src` tree belongs to.
    const srcSplit = target.indexOf('/src/')
    const projectDir = resolve(repoRoot, srcSplit === -1 ? target.replace(/\/src$/, '') : target.slice(0, srcSplit))
    if (!projectReferenceMatches(projectDir, references)) {
      problems.push(`${specifier} resolves to ${relative(repoRoot, projectDir)}, which packages/dsh-smart-assistant/tsconfig.json does not reference`)
    }
    if (!exists(join(repoRoot, target, 'index.ts'))) {
      problems.push(`${specifier} paths entry ${target} has no index.ts`)
    }
  }
  return problems
}

/**
 * The runtime tsconfig facade must be the generated file, name the packages the source launch
 * loads by name (so a stale facade cannot pass silently), and be the file the launcher points
 * tsx at — the gate follows the launcher contract, not the one-line package.json script.
 * @param {{ runtimeText: string, launcherText: string, loadedByBoot: string[] }} inputs
 * @returns {string[]} problems; the caller reports a missing file itself (I/O, not a judgement).
 */
export function runtimeTsconfigProblems({ runtimeText, launcherText, loadedByBoot }) {
  const problems = []
  if (!runtimeText.includes('GENERATED by scripts/generate/gen-paths.mjs')) problems.push('tsconfig.tsx.json is not the generated file')
  for (const name of loadedByBoot) {
    if (!runtimeText.includes(`"${name}"`)) problems.push(`tsconfig.tsx.json has no alias for ${name}`)
  }
  if (!launcherText.includes('tsconfig.tsx.json') || !launcherText.includes('TSX_TSCONFIG_PATH')) {
    problems.push('dev/env/dsh.mjs does not point tsx at tsconfig.tsx.json')
  }
  return problems
}

/**
 * Our `SKILL_NAME_PATTERN` must be literally the harness registry's pattern: a local copy that
 * drifts accepts names the provider rejects (or the reverse).
 * @param {{ ourSource: string, registrySource: string }} inputs - both source files, as text.
 * @returns {string[]} empty when the two patterns are the same literal.
 */
export function skillNameGrammarProblems({ ourSource, registrySource }) {
  const ours = /SKILL_NAME_PATTERN = (\/.*\/)/.exec(ourSource)?.[1]
  const theirs = /const SKILL_NAME = (\/.*\/)/.exec(registrySource)?.[1]
  if (ours === undefined || theirs === undefined) return ['could not read one of the skill-name patterns']
  return ours === theirs ? [] : [`our pattern ${ours} differs from the registry's ${theirs}`]
}

/**
 * Every frontmatter key we write must be a key the provider actually reads: the provider reads
 * fields by property access (`data.metadata`), so the identifier must appear in its source.
 * @param {{ providerSource: string, keys: string[] }} inputs
 * @returns {string[]} one problem per key the provider never reads.
 */
export function skillFrontmatterKeyProblems({ providerSource, keys }) {
  const problems = []
  for (const key of keys) {
    if (!new RegExp(`\\b${key}\\b`).test(providerSource)) {
      problems.push(`provider source never reads frontmatter key ${key}`)
    }
  }
  return problems
}

// ── gate wiring ──────────────────────────────────────────────────────────────────────────────

/**
 * A check core that exists in verify-checks.mjs but is never invoked by verify.mjs is a script,
 * not a gate — the top-level command would never run it, so no invalid case could reach a real
 * acceptance path. The import statement itself proves nothing about invocation (and neither does
 * a bare name in a comment), so import lines are stripped and the core must be *called* at least
 * once in the runner's body — named import or namespace call both count as wired. Functions only:
 * shared constants (e.g. a status regex) are data for cores and specs, not gates.
 *
 * @param {{ exportedCores: Record<string, unknown>, verifySource: string }} inputs
 */
export function gateWiringProblems({ exportedCores, verifySource }) {
  const problems = []
  const functions = Object.entries(exportedCores).filter(([, value]) => typeof value === 'function')
  if (functions.length === 0) return ['the core module exports no functions — the wiring check has nothing to see']
  const body = verifySource.split('\n').filter(line => !/^\s*import\b/.test(line)).join('\n')
  for (const [name] of functions) {
    if (!body.includes(name)) {
      problems.push(`${name} is exported by verify-checks.mjs but never invoked in the body of verify.mjs (the import line does not count) — a script that exists is not a gate that runs; wire the call or drop the export`)
    }
  }
  return problems
}
