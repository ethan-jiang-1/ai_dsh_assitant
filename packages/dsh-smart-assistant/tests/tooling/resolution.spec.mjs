/**
 * Fixtures for the resolution and gate-wiring cores
 * (scripts/checks/gates/resolution.mjs). The wiring fixture imports the verify-checks BARREL
 * on purpose: exportedCores must be the full wired surface — a family-only namespace would
 * weaken the every-core-is-invoked assertion it exists to make.
 *
 * Plain .mjs on purpose: vitest runs it, `tsc -p tsconfig.test.json` does not type-check it
 * (same contract as the other tooling specs).
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { describe, expect, it } from 'vitest'
import {
  gateWiringProblems,
  importResolutionProblems,
  notesNamingProblems,
  notesStateProblems,
  runtimeTsconfigProblems,
  skillFrontmatterKeyProblems,
  skillNameGrammarProblems,
} from '../../../../scripts/checks/gates/resolution.mjs'
import { projectReferenceMatches } from '../../../../scripts/checks/gates/shared.mjs'
import * as gateCores from '../../../../scripts/checks/verify-checks.mjs'

describe('projectReferenceMatches (gates/shared.mjs) accepts pinned face leaves only', () => {
  it('accepts root/Host/Client references and rejects a sibling or arbitrary config', () => {
    const owner = '/fixture/vendor/connection'
    expect(projectReferenceMatches(owner, [owner])).toBe(true)
    expect(projectReferenceMatches(owner, [join(owner, 'tsconfig.host.json')])).toBe(true)
    expect(projectReferenceMatches(owner, [join(owner, 'tsconfig.client.json')])).toBe(true)
    expect(projectReferenceMatches(owner, ['/fixture/vendor/other/tsconfig.host.json'])).toBe(false)
    expect(projectReferenceMatches(owner, [join(owner, 'unrelated.json')])).toBe(false)
    expect(projectReferenceMatches(owner, [])).toBe(false)
  })
})

describe('importResolutionProblems', () => {
  const fixture = ({ baseEntries, references, sources, present }) => ({
    repoRoot: '/fixture/repo',
    packageDir: '/fixture/repo/packages/ours',
    baseText: `{\n  "compilerOptions": {\n    "paths": {\n${baseEntries}\n    }\n  }\n}`,
    projectConfigText: `{ "references": [${references}] }`,
    sources,
    exists: path => present.includes(path),
  })
  const ENTRY = '      "@deepseek-ai/dsh-tools": ["vendor/dsh/packages/core/tools/src"]'
  const REFERENCE = '{ "path": "../../vendor/dsh/packages/core/tools" }'
  const SOURCE = [{ path: '/fixture/repo/packages/ours/src/index.ts', text: "import { defineTool } from '@deepseek-ai/dsh-tools'" }]
  const TARGET_INDEX = '/fixture/repo/vendor/dsh/packages/core/tools/src/index.ts'
  const green = { baseEntries: ENTRY, references: REFERENCE, sources: SOURCE, present: [TARGET_INDEX] }

  it('accepts an import whose paths entry is backed by a referenced project with an index.ts', () => {
    expect(importResolutionProblems(fixture(green))).toEqual([])
  })

  it('flags an import with no paths entry in tsconfig.base.json', () => {
    const problems = importResolutionProblems(fixture({ ...green, baseEntries: '      "@deepseek-ai/other": ["x/src"]' }))
    expect(problems).toHaveLength(1)
    expect(problems[0]).toContain('has no paths entry')
  })

  it('flags a paths entry whose owning project the package does not reference', () => {
    const problems = importResolutionProblems(fixture({ ...green, references: '{ "path": "../../vendor/elsewhere" }' }))
    expect(problems.some(problem => problem.includes('does not reference'))).toBe(true)
  })

  it('flags a paths entry with no index.ts, and accepts the pinned host/client face references', () => {
    expect(importResolutionProblems(fixture({ ...green, present: [] })).some(problem => problem.includes('has no index.ts'))).toBe(true)
    const owner = '/fixture/repo/vendor/dsh/packages/core/tools'
    expect(importResolutionProblems(fixture({ ...green, references: `{ "path": "${owner}/tsconfig.host.json" }` }))).toEqual([])
    expect(importResolutionProblems(fixture({ ...green, references: `{ "path": "${owner}/tsconfig.client.json" }` }))).toEqual([])
  })
})

describe('runtimeTsconfigProblems', () => {
  const GENERATED = '// GENERATED by scripts/generate/gen-paths.mjs\n"@deepseek-ai/dsh-app-boot": {}'
  const LAUNCHER = "process.env.TSX_TSCONFIG_PATH = 'tsconfig.tsx.json'"
  const green = { runtimeText: GENERATED, launcherText: LAUNCHER, loadedByBoot: ['@deepseek-ai/dsh-app-boot'] }

  it('accepts the generated facade, every boot-loaded alias, and a launcher that points at it', () => {
    expect(runtimeTsconfigProblems(green)).toEqual([])
  })

  it('flags a facade that is not the generated file, misses an alias, or is not what the launcher reads', () => {
    expect(runtimeTsconfigProblems({ ...green, runtimeText: '"@deepseek-ai/dsh-app-boot": {}' })).toHaveLength(1)
    expect(runtimeTsconfigProblems({ ...green, loadedByBoot: ['@deepseek-ai/dsh-agent-preset-registry'] })).toHaveLength(1)
    expect(runtimeTsconfigProblems({ ...green, launcherText: 'node dsh.mjs' })).toHaveLength(1)
  })
})

describe('skillNameGrammarProblems', () => {
  const ours = 'const SKILL_NAME_PATTERN = /^[a-z][a-z0-9-]*$/u'
  const theirs = 'const SKILL_NAME = /^[a-z][a-z0-9-]*$/u'

  it('accepts our pattern when it is literally the registry pattern', () => {
    expect(skillNameGrammarProblems({ ourSource: ours, registrySource: theirs })).toEqual([])
  })

  it('flags a drifted copy and an unreadable pair', () => {
    const drifted = skillNameGrammarProblems({ ourSource: 'const SKILL_NAME_PATTERN = /^[A-Z]+$/u', registrySource: theirs })
    expect(drifted).toHaveLength(1)
    expect(drifted[0]).toContain("differs from the registry's")
    expect(skillNameGrammarProblems({ ourSource: 'nothing here', registrySource: 'nothing here' }))
      .toEqual(['could not read one of the skill-name patterns'])
  })
})

describe('skillFrontmatterKeyProblems', () => {
  const provider = 'const { name, description, whenToUse, metadata } = data'

  it('accepts keys the provider reads and flags a key it never mentions', () => {
    expect(skillFrontmatterKeyProblems({ providerSource: provider, keys: ['name', 'description', 'whenToUse', 'metadata'] })).toEqual([])
    const problems = skillFrontmatterKeyProblems({ providerSource: provider, keys: ['name', 'allowedTools'] })
    expect(problems).toHaveLength(1)
    expect(problems[0]).toContain('never reads frontmatter key allowedTools')
  })
})

describe('gateWiringProblems', () => {
  const verifySource = readFileSync(join(import.meta.dirname, '..', '..', '..', '..', 'scripts', 'checks', 'verify.mjs'), 'utf8')
  const functionCores = () => Object.entries(gateCores).filter(([, value]) => typeof value === 'function')

  it('accepts the real runner: every exported function core is invoked in the body', () => {
    expect(gateCores.gateWiringProblems({ exportedCores: gateCores, verifySource })).toEqual([])
  })

  it('accepts namespace-style wiring: one body call per core, no named imports', () => {
    // The shape this gate must not false-positive (the first draft's occurrence-count rule did):
    // a core called once via the namespace runs — it is wired.
    const source = functionCores().map(([name]) => `checks.push(gateCores.${name}(...))`).join('\n')
    expect(gateCores.gateWiringProblems({ exportedCores: gateCores, verifySource: source })).toEqual([])
  })

  it('flags a core reduced to its import line (call sites erased) as an unwired gate', () => {
    const name = 'notesNamingProblems'
    const first = verifySource.indexOf(name)
    const head = verifySource.slice(0, first + name.length)
    const tail = verifySource.slice(first + name.length).replaceAll(name, '')
    const problems = gateCores.gateWiringProblems({ exportedCores: gateCores, verifySource: head + tail })
    expect(problems).toHaveLength(1)
    expect(problems[0]).toContain(name)
    expect(problems[0]).toContain('never invoked in the body')
  })

  it('flags a core named nowhere in the runner', () => {
    const name = 'notesStateProblems'
    const problems = gateCores.gateWiringProblems({ exportedCores: gateCores, verifySource: verifySource.replaceAll(name, '') })
    expect(problems).toHaveLength(1)
    expect(problems[0]).toContain(name)
    expect(problems[0]).toContain('never invoked in the body')
  })

  it('reports an empty core module rather than passing silently', () => {
    expect(gateCores.gateWiringProblems({ exportedCores: {}, verifySource }).join(' ')).toContain('no functions')
  })
})
