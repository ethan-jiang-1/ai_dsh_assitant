import { existsSync, mkdirSync, readFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { defineConfig } from 'vitest/config'

/**
 * Resolve every `@deepseek-ai/*` workspace package to the **vendor source**, reusing the alias list
 * `pnpm gen-paths` already generates for the runtime (`tsconfig.tsx.json`).
 *
 * Why the tests follow the runtime instead of the built `lib/`: the pinned checkout's `lib/` is
 * gitignored build output. After a pin move it describes the *previous* pin (a stale `lib/` makes
 * vitest run old vendor code), and the vendor's own `build:lib` cannot rebuild from a clean tree —
 * its tsdown entry for the **root** package (`lib/types/{index,invariant,startup}.js`) is produced
 * by an internal generation step that no published script performs. Resolving source sidesteps both.
 *
 * Three traps this pays for (all hit once, 2026-09-25):
 *   1. generated targets are **repo-root-relative** — resolve against the repo root, not this file;
 *   2. vite needs an **entry file**, not a directory — prefer `src/index.ts`;
 *   3. nested `vendor/dsh/vendor/*` packages are absent from the generated list — add them by their
 *      declared `package.json` name (directory name ≠ package name, e.g. `group` →
 *      `@deepseek-ai/cordis-plugin-group`), and skip targets whose source does not exist.
 */
const repositoryRoot = new URL('../../', import.meta.url)

/**
 * Temporary root for the test process, inside the repo: `<repo>/.tmp/vitest/`.
 *
 * Why in-repo (root `AGENTS.md` hard rule 8): the file sandbox only allows the session workspace, so
 * every write to the system temp root (`os.tmpdir()` → `/tmp`, `/var/folders/...`, `%TEMP%`) is
 * denied and turns into one human approval prompt **per write**. `<repo>/.tmp/<purpose>/` is
 * therefore the only temporary location this repo uses; `.gitignore` ignores `.tmp/`.
 *
 * Why one edit here instead of ~30 call sites: `os.tmpdir()` re-reads the environment on **every**
 * call (POSIX: `TMPDIR`), so the fixtures in `tests/` keep calling it unchanged — every `mkdtemp`
 * they create lands under this root, and the package has one owner for the convention. `TMP`/`TEMP`
 * are the Windows/macOS spellings of the same knob; setting all three keeps the redirect
 * platform-independent.
 *
 * Why `test.env` (verified against the installed vitest, not assumed): the pool merges it **last**
 * into each worker's spawn env (`{ ...process.env, ...options.env, ...ctx.config.env, ...project.config.env }`),
 * so it overrides an inherited `TMPDIR` instead of losing to it — a `??=`-style fallback would have
 * silently kept the system temp root. `setupFiles` is the fallback only if a future pool stops
 * forwarding config env. Verified end-to-end: a spec's `mkdtemp` leaf landed at
 * `<repo>/.tmp/vitest/assistant-layout-*` while the system temp root gained nothing.
 *
 * The parent must exist before any spec runs: `mkdtemp` creates the leaf but not its parents, so a
 * missing `.tmp/vitest/` fails with ENOENT. Creating it at config load also covers `--run` (the
 * config is evaluated in the main process before any worker spawns).
 */
const temporaryRoot = fileURLToPath(new URL('.tmp/vitest', repositoryRoot))
mkdirSync(temporaryRoot, { recursive: true })

/** Prefer the package's source entry; fall back to the directory when there is no `index.ts`. */
function entryOf(directoryUrl) {
  const directory = fileURLToPath(directoryUrl).replace(/\/$/, '')
  const index = `${directory}/index.ts`
  return existsSync(index) ? index : directory
}

/** Runtime aliases generated by `pnpm gen-paths`, filtered to targets that exist. */
function runtimeAliases() {
  const text = readFileSync(new URL('tsconfig.tsx.json', repositoryRoot), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .filter(line => !line.trimStart().startsWith('//'))
    .join('\n')
  const entries = []
  for (const [specifier, targets] of Object.entries(JSON.parse(text).compilerOptions.paths)) {
    const target = Array.isArray(targets) ? targets[0] : undefined
    if (typeof target !== 'string' || specifier.includes('*') || target.includes('*')) continue
    const directory = new URL(target, repositoryRoot)
    if (!existsSync(directory)) continue
    entries.push({ specifier, entry: entryOf(directory) })
  }
  return entries
}

/** Nested vendor packages (`vendor/dsh/vendor/*`), keyed by their declared package name. */
function nestedVendorAliases() {
  const vendorRoot = new URL('vendor/dsh/vendor/', repositoryRoot)
  const entries = []
  for (const directory of readdirSync(vendorRoot)) {
    const manifest = new URL(`${directory}/package.json`, vendorRoot)
    const source = new URL(`${directory}/src/`, vendorRoot)
    if (!existsSync(manifest) || !existsSync(source)) continue
    const { name } = JSON.parse(readFileSync(manifest, 'utf8'))
    if (typeof name === 'string' && name.length > 0) entries.push({ specifier: name, entry: entryOf(source) })
  }
  return entries
}

/**
 * Subpath exports (`@scope/pkg/projection`) are NOT prefix-aliasable: the package-root alias
 * would rewrite them to `src/index.ts/projection`, which is not a file (hit when the
 * knowledge-approve row pulled session-format-catalog into the composition tests). Each
 * `./sub` export maps back to its source file by the vendor convention `lib/types/<name>.js`
 * ↔ `src/<name>.ts`; the alias is a plain string (exact match), so it cannot shadow the
 * package root even though it sorts after it.
 */
function subpathAliases() {
  const entries = []
  const text = readFileSync(new URL('tsconfig.tsx.json', repositoryRoot), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .filter(line => !line.trimStart().startsWith('//'))
    .join('\n')
  const paths = JSON.parse(text).compilerOptions.paths
  for (const [specifier, targets] of Object.entries(paths)) {
    const target = Array.isArray(targets) ? targets[0] : undefined
    if (typeof target !== 'string' || specifier.includes('*') || target.includes('*')) continue
    // tsconfig targets end at the package's `src/`; the manifest lives one level up.
    const packageDirUrl = pathToFileURL(`${join(repositoryRoot.pathname, target, '..')}/`)
    const manifest = new URL('package.json', packageDirUrl)
    if (!existsSync(manifest)) continue
    const pkg = JSON.parse(readFileSync(manifest, 'utf8'))
    for (const [sub, subTarget] of Object.entries(pkg.exports ?? {})) {
      if (sub === '.' || sub === './package.json' || sub.includes('*')) continue
      const js = typeof subTarget === 'string' ? subTarget : subTarget?.default
      if (typeof js !== 'string' || !js.startsWith('./lib/')) continue
      const sourceName = js.replace('./lib/types/', '').replace('./lib/', '').replace(/\.js$/, '')
      const sourceUrl = new URL(`src/${sourceName}.ts`, packageDirUrl)
      if (!existsSync(sourceUrl)) continue
      entries.push({ specifier: `${specifier}/${sub.replace(/^\.\//, '')}`, entry: fileURLToPath(sourceUrl), exact: true })
    }
  }
  return entries
}

const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

export default defineConfig({
  // Fixture temp roots land in `<repo>/.tmp/vitest/` — see `temporaryRoot` above for why, and for
  // why this one knob is enough for every `mkdtemp` fixture in `tests/`.
  test: {
    // The corpus-links gate fixtures spawn the full verify runner (a few hundred ms normally);
    // under a parallel `pnpm start`/preflight load the 5s default turned that into a flake.
    // The timeout only bounds waiting for a real subprocess; it does not retry or sleep.
    testTimeout: 20_000,
    env: {
      TMPDIR: temporaryRoot,
      TMP: temporaryRoot,
      TEMP: temporaryRoot,
    },
  },
  resolve: {
    // Longest specifier first so `@scope/a` cannot shadow `@scope/a-longer`. Exact subpath
    // entries (string find = exact match) sort before every prefix regex by their length.
    alias: [...subpathAliases(), ...runtimeAliases(), ...nestedVendorAliases()]
      .sort((left, right) => right.specifier.length - left.specifier.length)
      .map(entry => (entry.exact === true
        ? { find: entry.specifier, replacement: entry.entry }
        : { find: new RegExp(`^${escape(entry.specifier)}(?=/|$)`), replacement: entry.entry })),
  },
})
