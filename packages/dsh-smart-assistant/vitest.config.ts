import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vitest/config'

/**
 * Resolve every `@deepseek-ai/*` workspace package to the **vendor source**, reusing the alias list
 * `pnpm gen-paths` already generates for the runtime (`tsconfig.tsx.json`).
 *
 * Why the tests follow the runtime instead of the built `lib/`: the pinned checkout's `lib/` is
 * gitignored build output. After a pin move it describes the *previous* pin (a stale `lib/` makes
 * vitest run old vendor code), and the vendor's own `build:lib` cannot rebuild from a clean tree —
 * its tsdown entry for the **root** package (`lib/types/{index,invariant,startup}.js`) is produced
 * by an internal generation step that no published script performs. Resolving source sidesteps both.
 *
 * Three traps this pays for (all hit once, 2026-09-25):
 *   1. generated targets are **repo-root-relative** — resolve against the repo root, not this file;
 *   2. vite needs an **entry file**, not a directory — prefer `src/index.ts`;
 *   3. nested `vendor/dsh/vendor/*` packages are absent from the generated list — add them by their
 *      declared `package.json` name (directory name ≠ package name, e.g. `group` →
 *      `@deepseek-ai/cordis-plugin-group`), and skip targets whose source does not exist.
 */
const repositoryRoot = new URL('../../', import.meta.url)

/** Prefer the package's source entry; fall back to the directory when there is no `index.ts`. */
function entryOf(directoryUrl) {
  const directory = fileURLToPath(directoryUrl).replace(/\/$/, '')
  const index = `${directory}/index.ts`
  return existsSync(index) ? index : directory
}

/** Runtime aliases generated by `pnpm gen-paths`, filtered to targets that exist. */
function runtimeAliases() {
  const text = readFileSync(new URL('tsconfig.tsx.json', repositoryRoot), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .filter(line => !line.trimStart().startsWith('//'))
    .join('\n')
  const entries = []
  for (const [specifier, targets] of Object.entries(JSON.parse(text).compilerOptions.paths)) {
    const target = Array.isArray(targets) ? targets[0] : undefined
    if (typeof target !== 'string' || specifier.includes('*') || target.includes('*')) continue
    const directory = new URL(target, repositoryRoot)
    if (!existsSync(directory)) continue
    entries.push({ specifier, entry: entryOf(directory) })
  }
  return entries
}

/** Nested vendor packages (`vendor/dsh/vendor/*`), keyed by their declared package name. */
function nestedVendorAliases() {
  const vendorRoot = new URL('vendor/dsh/vendor/', repositoryRoot)
  const entries = []
  for (const directory of readdirSync(vendorRoot)) {
    const manifest = new URL(`${directory}/package.json`, vendorRoot)
    const source = new URL(`${directory}/src/`, vendorRoot)
    if (!existsSync(manifest) || !existsSync(source)) continue
    const { name } = JSON.parse(readFileSync(manifest, 'utf8'))
    if (typeof name === 'string' && name.length > 0) entries.push({ specifier: name, entry: entryOf(source) })
  }
  return entries
}

const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

export default defineConfig({
  resolve: {
    // Longest specifier first so `@scope/a` cannot shadow `@scope/a-longer`.
    alias: [...runtimeAliases(), ...nestedVendorAliases()]
      .sort((left, right) => right.specifier.length - left.specifier.length)
      .map(entry => ({ find: new RegExp(`^${escape(entry.specifier)}(?=/|$)`), replacement: entry.entry })),
  },
})
